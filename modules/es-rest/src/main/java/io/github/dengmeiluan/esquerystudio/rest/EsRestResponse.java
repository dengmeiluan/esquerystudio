package io.github.dengmeiluan.esquerystudio.rest;

/** Transport-neutral result of one Elasticsearch REST call. */
public final class EsRestResponse {

    private final int status;
    private final String body;

    public EsRestResponse(int status, String body) {
        this.status = status;
        this.body = body == null ? "" : body;
    }

    public int status() {
        return status;
    }

    public String body() {
        return body;
    }
}
